#Requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.5.0' }

# Variables set in BeforeAll are used inside It blocks, which the analyzer cannot see
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseDeclaredVarsMoreThanAssignments', '', Justification = 'Pester scoping')]
param()

BeforeAll {
    $root = Split-Path -Path $PSScriptRoot -Parent
    $build = & (Join-Path $root 'tools\Build-Release.ps1') -OutputPath (Join-Path $TestDrive 'dist')
    $extracted = Join-Path $TestDrive 'extracted'
    Expand-Archive -Path $build.Zip -DestinationPath $extracted
    $package = Join-Path $extracted "ADFlow-$($build.Version)"
}

Describe 'Release package' {
    It 'is named after the version in src\Audit.ps1' {
        $build.Version | Should -Match '^\d+\.\d+\.\d+$'
        Split-Path -Path $build.Zip -Leaf | Should -Be "ADFlow-$($build.Version).zip"
    }

    It 'has a CHANGELOG section for that version' {
        [IO.File]::ReadAllText((Join-Path $root 'CHANGELOG.md')) | Should -Match ('(?m)^## \[' + [regex]::Escape($build.Version) + '\]')
    }

    It 'publishes a checksum that matches the zip' {
        $line = [IO.File]::ReadAllText("$($build.Zip).sha256")
        $line | Should -BeLike "$((Get-FileHash -Path $build.Zip -Algorithm SHA256).Hash.ToLowerInvariant())  ADFlow-*.zip*"
    }

    It 'contains every source, settings and sample file' {
        foreach ($folder in 'src', 'config', 'demo') {
            foreach ($source in Get-ChildItem -Path (Join-Path $root $folder) -File) {
                Join-Path $package "$folder\$($source.Name)" | Should -Exist
            }
        }
        Join-Path $package 'tools\New-ADFlowLab.ps1' | Should -Exist
        Join-Path $package 'docs\LAB.es.md' | Should -Exist
    }

    It 'uses standard "/" separators inside the zip' {
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        $archive = [IO.Compression.ZipFile]::OpenRead($build.Zip)
        try { @($archive.Entries | Where-Object { $_.FullName.Contains('\') }) | Should -HaveCount 0 }
        finally { $archive.Dispose() }
    }

    It 'leaves out tests, screenshots and the release tooling' {
        Join-Path $package 'tests' | Should -Not -Exist
        Join-Path $package 'docs\onboarding-report.png' | Should -Not -Exist
        Join-Path $package 'tools\Build-Release.ps1' | Should -Not -Exist
    }

    It 'works once extracted' {
        $out = Join-Path $TestDrive 'run'
        $results = & (Join-Path $package 'ADFlow.ps1') -Action Onboard -CsvPath (Join-Path $package 'demo\new-hires.csv') -DryRun -PassThru `
            -LogPath (Join-Path $out 'runs') -MockStatePath (Join-Path $out 'mock.json') -HomeRoot (Join-Path $out 'no-share') 6> $null
        @($results | Where-Object Status -eq 'Planned').Count | Should -Be 8
        $summary = [IO.File]::ReadAllText((Join-Path $results[0].RunFolder 'summary.json')) | ConvertFrom-Json
        $summary.version | Should -Be $build.Version
        [IO.File]::ReadAllText((Join-Path $results[0].RunFolder 'report.html')) | Should -Match "Generated by ADFlow $([regex]::Escape($build.Version))"
    }
}
